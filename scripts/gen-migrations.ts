// Embeds migrations/*.sql into src/db/migrations.gen.ts so both runtimes apply the same SQL at startup.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(import.meta.dir, "..", "migrations");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const entries = files.map((f) => `  { name: ${JSON.stringify(f)}, sql: ${JSON.stringify(readFileSync(join(dir, f), "utf8"))} },`);
const out = `// Generated by scripts/gen-migrations.ts from migrations/*.sql. Do not edit.\nexport const MIGRATIONS: { name: string; sql: string }[] = [\n${entries.join("\n")}\n];\n`;
writeFileSync(join(import.meta.dir, "..", "src", "db", "migrations.gen.ts"), out);
console.log(`embedded ${files.length} migration(s)`);
